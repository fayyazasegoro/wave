export function DataLabel({ type }: { type: "demo" | "verified" | "ai_generated" | "estimated" | "hypothesis" }) {
  const config = {
    demo: { label: "Demo Data", className: "data-label-demo" },
    verified: { label: "Verified", className: "data-label-verified" },
    ai_generated: { label: "AI Generated", className: "data-label-ai" },
    estimated: { label: "Estimated", className: "data-label-ai" },
    hypothesis: { label: "Hypothesis", className: "data-label-demo" },
  };
  const { label, className } = config[type] || config.demo;
  return <span className={className}>{label}</span>;
}

export function DataDisclaimer({ type }: { type: "demo" | "verified" | "ai_generated" | "estimated" }) {
  if (type === "demo") {
    return (
      <div className="bg-warning/5 border border-warning/15 rounded-lg px-3 py-2 text-xs text-sage-light">
        ⚠️ <span className="font-medium text-warning">Demo Data</span> — This is illustrative data for demonstration. Not verified market research. Always validate independently before making business decisions.
      </div>
    );
  }
  if (type === "ai_generated") {
    return (
      <div className="bg-info/5 border border-info/15 rounded-lg px-3 py-2 text-xs text-sage-light">
        🤖 <span className="font-medium text-info">AI-Generated Insight</span> — This content was generated by AI based on available patterns. Treat as a hypothesis and validate with your own research.
      </div>
    );
  }
  return null;
}
